namespace AvaWpf;

/// <summary>The WPF theme families. Each reproduces a WPF theme dictionary as WPF draws it.</summary>
public enum ThemeFamily
{
    /// <summary>Windows 8 and 10 (<c>PresentationFramework.Aero2</c>).</summary>
    Aero2,

    /// <summary>Windows 8 "Aero Lite" (<c>PresentationFramework.AeroLite</c>).</summary>
    AeroLite,

    /// <summary>Windows Vista and 7 (<c>PresentationFramework.Aero</c>).</summary>
    Aero,

    /// <summary>Windows XP Luna: Blue, Silver (Metallic) and Olive Green (Homestead) (<c>PresentationFramework.Luna</c>).</summary>
    Luna,

    /// <summary>Windows XP Media Center Royale (<c>PresentationFramework.Royale</c>).</summary>
    Royale,

    /// <summary>Windows 98/2000 Classic with the Windows color schemes (<c>PresentationFramework.Classic</c>).</summary>
    Classic,

    /// <summary>Windows 11 Fluent (<c>PresentationFramework.Fluent</c>).</summary>
    Fluent,
}
