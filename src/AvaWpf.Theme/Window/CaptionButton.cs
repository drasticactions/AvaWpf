namespace AvaWpf;

/// <summary>A caption button of a <see cref="WindowFrame"/>.</summary>
public enum CaptionButton
{
    /// <summary>Minimize.</summary>
    Minimize,

    /// <summary>Maximize (shown while the window is normal).</summary>
    Maximize,

    /// <summary>Restore (shown while the window is maximized).</summary>
    Restore,

    /// <summary>Close.</summary>
    Close,
}
